#!/bin/bash
# =============================================================
#  RAQIB CTF — Writeup Logger
#  يسجّل خطوات حل CTF تلقائياً بصيغة Markdown
#  مع وقت كل خطوة + الأوامر المستخدمة + النتائج
# =============================================================

echo -e "${CYAN}╔══════════════════════════════════════════════════╗${NC}"
echo -e "${CYAN}║  📝 Writeup Logger — سجّل خطوات الحل              ║${NC}"
echo -e "${CYAN}║  يولّد writeup بصيغة Markdown جاهز للنشر         ║${NC}"
echo -e "${CYAN}╚══════════════════════════════════════════════════╝${NC}"
echo ""

# مجلد حفظ الـ writeups
WRITEUP_DIR="${HOME}/.raqib_writeups"
mkdir -p "$WRITEUP_DIR"

echo -e "  ${YELLOW}1)${NC} إنشاء writeup جديد"
echo -e "  ${YELLOW}2)${NC} إضافة خطوة لـ writeup موجود"
echo -e "  ${YELLOW}3)${NC} عرض writeup موجود"
echo -e "  ${YELLOW}4)${NC} تصدير writeup (Markdown)"
echo -e "  ${YELLOW}5)${NC} قائمة كل الـ writeups"
read -rp "  اختر: " mode
echo ""

list_writeups() {
    files=($(ls -t "$WRITEUP_DIR"/*.md 2>/dev/null))
    if [ ${#files[@]} -eq 0 ]; then
        echo -e "  ${YELLOW}لا توجد writeups محفوظة${NC}"
        return 1
    fi
    echo -e "  ${CYAN}الـ Writeups المحفوظة:${NC}"
    local i=1
    for f in "${files[@]}"; do
        name=$(basename "$f" .md)
        mtime=$(date -r "$f" '+%Y-%m-%d %H:%M' 2>/dev/null || stat -c '%y' "$f" 2>/dev/null | cut -d' ' -f1-2)
        echo -e "  ${CYAN}${i})${NC} ${name}  (${mtime})"
        ((i++))
    done
    return 0
}

pick_writeup() {
    list_writeups || return 1
    echo ""
    read -rp "  اختر رقم الـ writeup: " num
    files=($(ls -t "$WRITEUP_DIR"/*.md 2>/dev/null))
    local idx=$((num - 1))
    if [ "$idx" -ge 0 ] && [ "$idx" -lt "${#files[@]}" ]; then
        echo "${files[$idx]}"
        return 0
    fi
    echo -e "${RED}رقم غير صحيح${NC}" >&2
    return 1
}

case "$mode" in
    1)  # إنشاء جديد
        read -rp "  اسم التحدي (Challenge Name): " challenge_name
        [ -z "$challenge_name" ] && { echo -e "${RED}الاسم مطلوب${NC}"; exit 1; }
        read -rp "  اسم المسابقة (CTF Name): " ctf_name
        read -rp "  الفئة (Crypto/Web/Forensics/...): " category
        read -rp "  الصعوبة (Easy/Medium/Hard): " difficulty
        read -rp "  نقاط (Points): " points

        safe_name=$(echo "$challenge_name" | tr ' ' '_' | tr -cd 'A-Za-z0-9_-')
        timestamp=$(date +%Y%m%d_%H%M%S)
        writeup_file="$WRITEUP_DIR/${safe_name}_${timestamp}.md"

        cat > "$writeup_file" <<MDEOF
# ${challenge_name}

**CTF:** ${ctf_name:-Unknown CTF}
**Category:** ${category:-Unknown}
**Difficulty:** ${difficulty:-Unknown}
**Points:** ${points:-?}
**Date:** $(date '+%Y-%m-%d')
**Author:** $(whoami)

---

## Description

<!-- أضف وصف التحدي هنا -->

## Reconnaissance

<!-- ما الذي لاحظته أول مرة؟ -->

## Solution

### Step 1

**Time:** $(date '+%H:%M:%S')

<!-- وصف الخطوة -->

\`\`\`bash
# الأوامر المستخدمة
\`\`\`

**Output:**
\`\`\`
# النتيجة
\`\`\`

## Flag

\`\`\`
flag{...}
\`\`\`

## Lessons Learned

<!-- ماذا تعلمت من هذا التحدي؟ -->

---
*Generated by RAQIB CTF Writeup Logger v2.1*
MDEOF

        echo -e "  ${GREEN}✅ تم إنشاء: $writeup_file${NC}"
        echo ""
        echo -e "  ${CYAN}محتوى أولي:${NC}"
        cat "$writeup_file" | head -20
        ;;

    2)  # إضافة خطوة
        writeup_file=$(pick_writeup) || exit 1
        echo ""
        read -rp "  عنوان الخطوة: " step_title
        read -rp "  الأمر المستخدم (اختياري): " step_cmd
        read -rp "  النتيجة/الملاحظة: " step_result
        echo -e "  هل وجدت flag؟ (y/n): "
        read -r found_flag
        step_flag=""
        if [ "$found_flag" = "y" ]; then
            read -rp "  أدخل الـ flag: " step_flag
        fi

        step_num=$(grep -c "^### Step" "$writeup_file" 2>/dev/null)
        step_num=$((step_num + 1))

        # إضافة الخطوة قبل قسم Flag
        python3 - "$writeup_file" "$step_num" "$step_title" "$step_cmd" "$step_result" "$step_flag" <<'PYEOF'
import sys, re
writeup_file, step_num, title, cmd, result, flag = sys.argv[1:]

with open(writeup_file, 'r') as f:
    content = f.read()

step_block = f"""
### Step {step_num}

**Time:** {__import__('datetime').datetime.now().strftime('%H:%M:%S')}

{title}

"""
if cmd:
    step_block += f"```bash\n{cmd}\n```\n\n"
if result:
    step_block += f"**Output:**\n```\n{result}\n```\n"
if flag:
    step_block += f"\n**🏴 FLAG:** `{flag}`\n"

# أضف قبل قسم ## Flag
if '## Flag' in content:
    content = content.replace('## Flag', step_block + '\n## Flag')
else:
    content += step_block

with open(writeup_file, 'w') as f:
    f.write(content)

print(f"  ✅ تمت إضافة Step {step_num}")
PYEOF
        ;;

    3)  # عرض
        writeup_file=$(pick_writeup) || exit 1
        echo ""
        echo -e "${BOLD}══ محتوى الـ Writeup ══${NC}"
        cat "$writeup_file"
        ;;

    4)  # تصدير
        writeup_file=$(pick_writeup) || exit 1
        echo ""
        read -rp "  مسار التصدير (أو Enter للتصدير للمجلد الحالي): " export_path
        export_path="${export_path:-./$(basename "$writeup_file")}"
        cp "$writeup_file" "$export_path"
        echo -e "  ${GREEN}✅ تم تصدير: $export_path${NC}"
        echo ""
        echo -e "  ${CYAN}إحصائيات:${NC}"
        wc -l "$export_path" | awk '{print "  " $1 " سطر"}'
        grep -c "^### Step" "$export_path" 2>/dev/null | \
            xargs -I{} echo "  {} خطوة"
        ;;

    5)  # قائمة
        list_writeups
        ;;

    *)
        echo -e "${RED}اختيار غير صحيح${NC}"
        ;;
esac
